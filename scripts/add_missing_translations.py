# Load and update each locale file
locales = ['ku', 'en', 'ar', 'zh']
for locale in locales:
    filepath = f'/home/ubuntu/wazn-express/client/src/locales/{locale}.json'
    with open(filepath, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    # Add auto translations
    if 'auto' not in data:
        data['auto'] = {}
    
    if locale in missing_translations:
        for key, value in missing_translations[locale].items():
            if key not in data['auto']:
                data['auto'][key] = value
    
    # Add fullPackage translations
    if 'fullPackage' not in data:
        data['fullPackage'] = {}
    
    if locale in fullpackage_translations:
        for key, value in fullpackage_translations[locale].items():
            if key not in data['fullPackage']:
                data['fullPackage'][key] = value
    
    # Add common translations
    if 'common' not in data:
        data['common'] = {}
    
    if locale in common_translations:
        for key, value in common_translations[locale].items():
            if key not in data['common']:
                data['common'][key] = value
    
    # Save the file
    with open(filepath, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    
    print(f"Updated {locale}.json")

print("\nAll locale files updated!")
