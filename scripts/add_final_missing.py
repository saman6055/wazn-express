# Load and update each locale file
for locale, translations in final_translations.items():
    filepath = f'/home/ubuntu/wazn-express/client/src/locales/{locale}.json'
    with open(filepath, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    if 'auto' not in data:
        data['auto'] = {}
    
    for key, value in translations.items():
        if key not in data['auto']:
            data['auto'][key] = value
    
    with open(filepath, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    
    print(f"Updated {locale}.json with {len(translations)} keys")

