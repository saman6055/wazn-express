function readJson(filename) {
  const path = resolve(LOCALES_DIR, filename);
  return JSON.parse(readFileSync(path, 'utf-8'));
}

function writeJson(filename, data) {
  const path = resolve(LOCALES_DIR, filename);
  writeFileSync(path, JSON.stringify(data, null, 2) + '\n', 'utf-8');
}

/**
 * Recursively walk all keys in `source` (ku.json).
 * For each leaf string value, if `target[key] === kuValue`, replace with translation.
 * Returns count of updates.
 */
function translateObject(kuObj, targetObj, lang) {
  let count = 0;
  
  for (const key of Object.keys(kuObj)) {
    const kuVal = kuObj[key];
    
    if (typeof kuVal === 'object' && kuVal !== null && !Array.isArray(kuVal)) {
      // Nested object
      if (typeof targetObj[key] === 'object' && targetObj[key] !== null) {
        count += translateObject(kuVal, targetObj[key], lang);
      }
    } else if (typeof kuVal === 'string') {
      // Leaf string value
      if (targetObj[key] === kuVal) {
        // This value is untranslated (equals Kurdish)
        const trimmedKu = kuVal.trim();
        
        // Try exact match first
        if (translations[trimmedKu] && translations[trimmedKu][lang]) {
          targetObj[key] = translations[trimmedKu][lang];
          count++;
        } else if (translations[kuVal] && translations[kuVal][lang]) {
          targetObj[key] = translations[kuVal][lang];
          count++;
        }
      }
    }
  }
  
  return count;
}

