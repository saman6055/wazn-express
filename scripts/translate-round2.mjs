function readJson(filename) {
  const path = resolve(LOCALES_DIR, filename);
  return JSON.parse(readFileSync(path, 'utf-8'));
}

function writeJson(filename, data) {
  const path = resolve(LOCALES_DIR, filename);
  writeFileSync(path, JSON.stringify(data, null, 2) + '\n', 'utf-8');
}

/**
 * Apply key-based translations.
 * keyTranslations uses dot notation "section.key" → {en, ar, zh}
 */
function applyKeyTranslations(ku, target, lang) {
  let count = 0;
  for (const [dotKey, trans] of Object.entries(keyTranslations)) {
    const parts = dotKey.split('.');
    let kuNode = ku;
    let targetNode = target;
    
    // Navigate to parent
    for (let i = 0; i < parts.length - 1; i++) {
      if (!kuNode[parts[i]] || !targetNode[parts[i]]) break;
      kuNode = kuNode[parts[i]];
      targetNode = targetNode[parts[i]];
    }
    
    const lastKey = parts[parts.length - 1];
    if (kuNode && targetNode && typeof kuNode[lastKey] === 'string' && typeof targetNode[lastKey] === 'string') {
      // Only update if value equals Kurdish (untranslated)
      if (targetNode[lastKey] === kuNode[lastKey] && trans[lang]) {
        targetNode[lastKey] = trans[lang];
        count++;
      }
    }
  }
  return count;
}

/**
 * Apply value-based translations for auto section and any remaining values.
 * Recursively walks the entire object tree.
 */
function applyValueTranslations(kuObj, targetObj, lang) {
  let count = 0;
  for (const key of Object.keys(kuObj)) {
    const kuVal = kuObj[key];
    if (typeof kuVal === 'object' && kuVal !== null && !Array.isArray(kuVal)) {
      if (typeof targetObj[key] === 'object' && targetObj[key] !== null) {
        count += applyValueTranslations(kuVal, targetObj[key], lang);
      }
    } else if (typeof kuVal === 'string') {
      if (targetObj[key] === kuVal) {
        const trimmed = kuVal.trim();
        if (valueTranslations[kuVal] && valueTranslations[kuVal][lang]) {
          targetObj[key] = valueTranslations[kuVal][lang];
          count++;
        } else if (valueTranslations[trimmed] && valueTranslations[trimmed][lang]) {
          targetObj[key] = valueTranslations[trimmed][lang];
          count++;
        }
      }
    }
  }
  return count;
}

/**
 * Count remaining untranslated values (target === ku) 
 */
function countUntranslated(kuObj, targetObj) {
  let count = 0;
  for (const key of Object.keys(kuObj)) {
    const kuVal = kuObj[key];
    if (typeof kuVal === 'object' && kuVal !== null && !Array.isArray(kuVal)) {
      if (typeof targetObj[key] === 'object' && targetObj[key] !== null) {
        count += countUntranslated(kuVal, targetObj[key]);
      }
    } else if (typeof kuVal === 'string') {
      if (targetObj[key] === kuVal) {
        count++;
      }
    }
  }
  return count;
}

