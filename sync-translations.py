# Function to recursively merge translations
def merge_translations(source, target, path=""):
    result = {}
    for key in source:
        current_path = f"{path}.{key}" if path else key
        if isinstance(source[key], dict):
            if key in target and isinstance(target[key], dict):
                result[key] = merge_translations(source[key], target[key], current_path)
            else:
                result[key] = source[key]  # Keep Kurdish if no English
        else:
            if key in target:
                result[key] = target[key]
            else:
                result[key] = source[key]  # Keep Kurdish if no English translation
    return result

